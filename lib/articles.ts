export function getArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

export function getRelatedArticles(slug: string, limit = 6): Article[] {
  const article = getArticle(slug);
  if (!article) return articles.slice(0, limit);
  const related = article.related
    .map((s) => getArticle(s))
    .filter((a): a is Article => !!a);
  const remaining = articles.filter(
    (a) => a.slug !== slug && !article.related.includes(a.slug)
  );
  return [...related, ...remaining].slice(0, limit);
}

